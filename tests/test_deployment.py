    def test_recovery_can_resume_when_recovery_itself_is_interrupted(self):
        base, target = self.app()
        from blitzcam import offline_updater as updater
        # Leave a real partially switched tree and write-ahead journal.
        with patch.object(updater, 'recover', return_value=False), self.assertRaises(OSError):
            apply(base, base, self.package, self.trust, base/'output/deployment/crash', fault_after=4)
        count = 0
        def interrupted_write(path, value):
            nonlocal count
            write_json(path, value)
            count += 1
            if count == 2:
                raise OSError('Interrupted recovery')
        with patch.object(updater, 'write_json', side_effect=interrupted_write), self.assertRaises(OSError):
            recover(base, base)
        self.assertTrue(recover(base, base))
        self.assertEqual((base/'app/obsolete.txt').read_bytes(), b'old')
        self.assertEqual(json.loads((base/'manifest.json').read_text())['version'], '1')

