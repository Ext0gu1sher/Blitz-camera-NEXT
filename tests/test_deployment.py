class PackagePathTests(unittest.TestCase):
    def test_unsafe_windows_names(self):
        for name in ('../bad', '/bad', 'a//b', 'a/./b', 'a\\b', 'a:b', 'NUL.txt',
                     'COM1', 'a/b.', 'a/b ', 'a/../b', 'a/?', 'a/\0'):
            with self.subTest(name=name), self.assertRaises(ValueError):
                safe_name(name)

    def test_duplicate_case_and_hashes(self):
        with self.assertRaises(ValueError):
            file_map({'a': '0'*64, 'A': '1'*64})
        with self.assertRaises(ValueError):
            file_map({'a': 'not-a-hash'})

    def test_zip_traversal_duplicates_size_and_symlink(self):
        for names, limit, symlink in [(('../a',), 100, False), (('a','A'), 100, False),
                                      (('a',), 1, False), (('a',), 100, True)]:
            stream = io.BytesIO()
            with zipfile.ZipFile(stream, 'w') as z:
                for name in names:
                    entry = zipfile.ZipInfo(name)
                    if symlink:
                        entry.external_attr = 0o120777 << 16
                    z.writestr(entry, b'abc')
            with self.assertRaises(ValueError):
                read_zip(io.BytesIO(stream.getvalue()), limit=limit)

    def test_extra_payload_file(self):
        with self.assertRaises(ValueError):
            checked_payload(zip_bytes({'a': b'a', 'b': b'b'}), {'a': digest(b'a')})


@unittest.skipUnless(os.name == 'nt', 'Uses Windows CNG and DPAPI')
class DeploymentTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.public, cls.private = crypto.generate_publisher()
        cls.provider = 'Microsoft Software Key Storage Provider'
        cls.key_name = 'BlitzCamera-Test-' + uuid4().hex
        cls.device_public = crypto.device_public(cls.key_name, cls.provider, create=True)
        cls.device = {'key_name': cls.key_name, 'provider': cls.provider, 'device': digest(cls.device_public)}

    @classmethod
    def tearDownClass(cls):
        # Delete only the uniquely named key generated by this test class.
        with crypto.device_key(cls.key_name, cls.provider) as (dll, key):
            crypto._check(crypto._fn(dll, 'NCryptDeleteKey', [crypto.HANDLE, crypto.U32])(key, 0), '清理测试密钥')
            key.value = 0

    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.trust = self.root/'trust.json'
        write_json(self.trust, {'keys': {digest(self.public): base64.b64encode(self.public).decode('ascii')}})
        self.manager = Deployment(self.root/'output', root=self.root, trust=self.trust)
        write_json(self.manager.directory/'device.json', self.device)
        self.config = self.root/'device.bcconfig'
        self.manager.export_config(self.config)
        self.package = self.root/'package.bcupdate'

    def pro(self):
        return build_pro(ROOT/'blitzcam', self.config, self.package, version='11.21-r1',
                         game_sha256='5030ee4b9f6ec7db1c06efa2b92f9dd7243574be5d8d9578c118119318bc9608',
                         public=self.public, private=self.private)

    def release(self, root, version, *, extra=False):
        files = {'app/blitzcam/__init__.py': ('version='+repr(version)).encode(),
                 'app/blitzcam/server.py': version.encode(),
                 'app/obsolete.txt': b'old', 'runtime/pythonw.exe': b'unchanged-runtime',
                 'BlitzCamera.exe': b'unchanged-launcher', 'licenses/LICENSE': b'license'}
        if extra:
            files.pop('app/obsolete.txt')
            files['app/new.txt'] = b'new'
        for name, data in files.items():
            path = root/name; path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(data)
        write_json(root/'manifest.json', {'version': version, 'files': {n: digest(b) for n,b in files.items()}})
        return root

    def app(self):
        base = self.release(self.root/'install', '1')
        target = self.release(self.root/'target', '2', extra=True)
        build_app(base, target, self.package, public=self.public, private=self.private)
        return base, target

    def test_crypto_authenticated_roundtrip(self):
        signature = crypto.sign(self.private, b'test')
        crypto.verify(self.public, b'test', signature)
        with self.assertRaises(ValueError):
            crypto.verify(self.public, b'changed', signature)
        cipher, tag = crypto.aes_gcm(b'a'*32, b'b'*12, b'hello', b'context')
        clear, _ = crypto.aes_gcm(b'a'*32, b'b'*12, cipher, b'context', tag=tag)
        self.assertEqual(clear, b'hello')
        with self.assertRaises(ValueError):
            crypto.aes_gcm(b'a'*32, b'b'*12, cipher, b'changed', tag=tag)
        self.assertEqual(crypto.protect_local(crypto.protect_local(b'secret'), decrypt=True), b'secret')

    def test_config_contains_no_private_key_and_is_stable(self):
        first = json.loads(self.config.read_text(encoding='utf-8'))
        self.manager.export_config(self.config)
        self.assertEqual(first, json.loads(self.config.read_text(encoding='utf-8')))
        self.assertEqual(set(first), {'format','api','app_version','device','public_key','protection'})
        self.assertEqual(crypto.validate_public(base64.b64decode(first['public_key'])), self.device['device'])

    def test_publisher_backup_restore_and_wrong_password(self):
        key = self.root/'publisher.dpapi'; key.write_bytes(crypto.protect_local(self.private))
        backup = self.root/'backup.bcsecret'
        backup_key(key, self.trust, backup, 'test-only-long-password')
        restored = self.root/'restored.dpapi'
        with self.assertRaises(ValueError):
            restore_key(backup, restored, self.trust, 'wrong-password')
        self.assertFalse(restored.exists())
        restore_key(backup, restored, self.trust, 'test-only-long-password')
        self.assertEqual(crypto.protect_local(restored.read_bytes(), decrypt=True), self.private)

    def test_initially_hidden_and_backend_refuses_access(self):
        self.assertEqual(self.manager.status()['edition'], 'next')
        with self.assertRaises(CameraError):
            GameBackend(self.manager).connect()

    def test_signed_encrypted_import_and_memory_loading(self):
        self.pro()
        manifest, payload = read_signed(self.package, self.trust)
        self.assertNotIn(b'def config_for', payload)
        selected = self.manager.inspect(self.package)
        self.assertFalse(self.manager.enabled)  # preview is not activation
        result = self.manager.install(selected['token'])
        self.assertEqual(result['edition'], 'pro')
        backend = GameBackend(self.manager)
        module = backend.module('playback')  # imports real adapter, never calls game
        self.assertTrue(hasattr(module, 'PositionPlayback'))
        self.assertIs(backend.module('profile').CameraError, CameraError)
        self.assertFalse(list((self.manager.directory/'runtime').rglob('*.py')))
        self.assertTrue(list((self.manager.directory/'runtime').rglob('*.dll')))
        reloaded = Deployment(self.root/'output', root=self.root, trust=self.trust)
        self.assertTrue(reloaded.enabled)
        # Loaded adapters cannot be replaced underneath a running session.
        selected = self.manager.inspect(self.package)
        with self.assertRaisesRegex(ValueError, '重新启动'):
            self.manager.install(selected['token'], backend_loaded=True)

    def test_wrong_device_and_cipher_tampering(self):
        self.pro()
        manifest, payload = read_signed(self.package, self.trust)
        with self.assertRaisesRegex(ValueError, '不匹配'):
            decrypt_pro(manifest, payload, dict(self.device, device='f'*64))
        broken = payload[:-1] + bytes([payload[-1] ^ 1])
        with self.assertRaises(ValueError):
            decrypt_pro(manifest, broken, self.device)
        # Possessing a copied device.json cannot access the original OS key.
        with self.assertRaises(ValueError):
            decrypt_pro(manifest, payload, dict(self.device, key_name='missing-'+uuid4().hex))

    def test_encrypted_adapter_reads_active_replay_through_host_timeline(self):
        from unittest.mock import patch
        from test_replay_source import source_fixture
        from blitzcam.replay_timeline import file_timeline, session_timeline
        from blitzcam.profile import BuildProfile
        self.pro()
        self.manager.install(self.manager.inspect(self.package)['token'])
        backend = GameBackend(self.manager)
        replay = self.root/'manual replay.wotbreplay'
        with zipfile.ZipFile(replay, 'w') as archive:
            archive.writestr('meta.json', json.dumps({'version':'11.21.0', 'battleDuration':253.12938}))
        memory = source_fixture(replay, pointer_owner=True).memory
        memory.profile = backend.module('profile').PROFILE_1121
        session = backend.module('reader').CameraSession(memory)
        session.discover()
        self.assertNotIsInstance(session.profile, BuildProfile)
        # The encrypted adapter has its own profile class. The real host must
        # still read the active file; it must never inspect a process command line.
        with patch.object(crypto.C, 'WinDLL', side_effect=AssertionError('unexpected native query')):
            actual = session_timeline(session)
        self.assertEqual(actual['verification'], 'runtime_replay')
        self.assertEqual(actual['replay_sha256'], file_timeline(replay)['replay_sha256'])

    def test_pro_intro_survives_restart_and_is_consumed_only_by_its_token(self):
        self.assertEqual(self.manager.startup_state(), {'edition': 'next', 'intro_token': ''})
        self.pro()
        selected = self.manager.inspect(self.package)
        self.assertEqual(self.manager.startup_state()['intro_token'], '')
        self.manager.install(selected['token'])
        first = self.manager.startup_state()
        self.assertEqual(first['edition'], 'pro')
        self.assertRegex(first['intro_token'], r'^[0-9a-f]{32}$')
        reloaded = Deployment(self.root/'output', root=self.root, trust=self.trust)
        self.assertEqual(reloaded.startup_state(), first)
        self.assertFalse(reloaded.acknowledge_startup('stale'))
        self.assertEqual(reloaded.startup_state(), first)
        self.assertTrue(reloaded.acknowledge_startup(first['intro_token']))
        self.assertFalse(reloaded.acknowledge_startup(first['intro_token']))
        # Updating/reinstalling an already activated Pro does not replay the intro.
        selected = reloaded.inspect(self.package)
        reloaded.install(selected['token'])
        self.assertEqual(reloaded.startup_state(), {'edition': 'pro', 'intro_token': ''})

    def test_desktop_pro_upgrade_schedules_restart_and_blocks_game_until_exit(self):
        self.release(self.root, 'test-host')
        self.pro()
        selected = self.manager.inspect(self.package)
        self.assertTrue(selected['restart'])
        with patch('blitzcam.deployment.subprocess.Popen') as launch:
            result = self.manager.install(selected['token'], pids=[123, 456], restart_pro=True)
        self.assertTrue(result['restart'])
        self.assertFalse(result['reload'])
        self.assertTrue(self.manager.restart_pending)
        with self.assertRaises(CameraError): GameBackend(self.manager).require()
        job = json.loads(Path(launch.call_args.args[0][-1]).read_text(encoding='utf-8'))
        self.assertEqual(job['action'], 'restart')
        self.assertEqual(set(job['pids']), {os.getpid(),123,456})
        self.assertNotIn('package', job)
        reloaded = Deployment(self.root/'output', root=self.root, trust=self.trust)
        self.assertFalse(reloaded.restart_pending)
        self.assertTrue(reloaded.startup_state()['intro_token'])
        # A later component update can restart even after its old module loaded.
        reloaded.acknowledge_startup(reloaded.startup_state()['intro_token'])
        backend = GameBackend(reloaded); backend.module('reader')
        with patch('blitzcam.deployment.subprocess.Popen'):
            later = reloaded.install(reloaded.inspect(self.package)['token'], backend_loaded=True, restart_pro=True)
        self.assertTrue(later['restart'])
        self.assertFalse(reloaded.startup_state()['intro_token'])

