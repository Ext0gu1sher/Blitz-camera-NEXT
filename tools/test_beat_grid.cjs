const assert=require('node:assert/strict');
const B=require('../blitzcam/web/beat-grid.js'),{ClockMap}=require('../blitzcam/web/timeline.js');
const timeline={duration_sec:100,work_start_sec:10,work_end_sec:30};
const speed={mode:'fixed',rate:.25,camera_clock:'replay',keyframes:[{progress:0,rate:1},{progress:1,rate:1}]};
const map=new ClockMap({x:[]},speed,timeline),settings={...B.defaults(),enabled:true};
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-6,`${a} != ${b}`);
let grid=B.grid(settings,map);near(B.timeAt(grid,0),10);near(B.timeAt(grid,1),10.125);assert.equal(grid.count,161);
near(B.nearest(grid,10.13),10.125);
grid=B.grid({...settings,offset_sec:-.25},map);near(B.timeAt(grid,grid.first),10.0625);
grid=B.grid({...settings,origin:'playhead',anchor_sec:15},map);near(B.timeAt(grid,0),15);
assert.equal(B.grid({...settings,origin:'playhead',anchor_sec:200},map).count,0);
assert.equal(B.grid({...settings,enabled:false},map),null);
const moved=new ClockMap({x:[]},speed,{...timeline,work_start_sec:12});near(B.timeAt(B.grid(settings,moved),0),12);
const curve=new ClockMap({x:[]},{...speed,mode:'curve',interpolation:'linear',keyframes:[{progress:0,rate:1},{progress:.5,rate:.125},{progress:1,rate:1}]},timeline);
grid=B.grid({...settings,bpm:133.5,division:2},curve);
for(let i=grid.first;i<grid.last;i++)near(curve.atTime(B.timeAt(grid,i+1))-curve.atTime(B.timeAt(grid,i)),grid.step);
const long=new ClockMap({x:[]},{...speed,rate:.0625},{duration_sec:3600,work_start_sec:0,work_end_sec:3600});
grid=B.grid({...settings,bpm:300,division:4},long);assert.ok(grid.count>1e6);
assert.ok(B.visible(grid,0,3600,120).length<=120);near(B.nearest(grid,3599.9),3599.9);
console.log('PASS shooting-time cadence, speed curves, origins, trim, offsets, disabled grid and bounded rendering with exact snapping');
